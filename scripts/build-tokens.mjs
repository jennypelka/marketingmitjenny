// Generates src/styles/tokens.css from design-system/tokens.json (single source of truth).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const t = JSON.parse(readFileSync('design-system/tokens.json', 'utf8'));
const ref = (v) => v.replace(/\{([a-z0-9-]+)\}/g, 'var(--$1)');
const out = [];

const base = [];
const light = [];
const dark = [];

for (const c of t.color.tokens) {
  if (typeof c.value === 'string') base.push(`--${c.name}: ${ref(c.value)};`);
  else {
    light.push(`--${c.name}: ${ref(c.value.light)};`);
    dark.push(`--${c.name}: ${ref(c.value.dark)};`);
  }
}
for (const s of t.spacing.tokens) base.push(`--${s.name}: ${s.value};`);
for (const r of t.radius.tokens) base.push(`--${r.name}: ${r.value};`);
for (const l of t.layout.tokens) base.push(`--${l.name}: ${l.value};`);
for (const s of t.shadow.tokens) {
  light.push(`--${s.name}: ${s.value.light};`);
  dark.push(`--${s.name}: ${s.value.dark};`);
}
base.push(`--font-display: ${t.type.families.display};`);
base.push(`--font-sans: ${t.type.families.sans};`);

const block = (sel, decls, extra = '') => `${sel} {\n  ${decls.join('\n  ')}${extra}\n}`;

out.push('/* GENERATED by scripts/build-tokens.mjs from design-system/tokens.json. Do not edit. */');
out.push(block(':root', [...base, ...light], '\n  color-scheme: light;'));
out.push(`@media (prefers-color-scheme: dark) {\n${block('  :root:not([data-theme="light"])', dark, '\n  color-scheme: dark;').replace(/^/gm, '  ').replace(/^ {2} {2}/, '  ')}\n}`);
out.push(block(':root[data-theme="dark"],\n[data-theme="dark"]', dark, '\n  color-scheme: dark;'));

mkdirSync('src/styles', { recursive: true });
writeFileSync('src/styles/tokens.css', out.join('\n\n') + '\n');
console.log('tokens.css written');
